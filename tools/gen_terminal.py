#!/usr/bin/env python3
"""Emit terminal-emulator colour schemes from the generated Neovim palette.

Keeps the terminal, tmux and Neovim on one palette so the editor background
does not sit on a differently-shaded terminal background.
"""
import re, sys, os, json

def read_palette(lua_path):
    src = open(lua_path, encoding='utf-8').read()
    body = src.split('M.palette = {', 1)[1]
    p, ansi = {}, {}
    depth, in_ansi = 0, False
    for line in body.split('\n'):
        if line.strip().startswith('}') and in_ansi:
            in_ansi = False; continue
        if line.strip().startswith('}') and not in_ansi:
            break
        if 'ansi = {' in line:
            in_ansi = True; continue
        m = re.match(r"\s*(\w+)\s*=\s*\"(#[0-9A-Fa-f]{6})\"", line)
        if m:
            (ansi if in_ansi else p)[m.group(1)] = m.group(2)
    return p, ansi

def alacritty(p, a):
    def q(c): return '"%s"' % c
    return f'''# VS Code Dark 2026 -- generated by tools/gen_terminal.py
# Import from alacritty.toml:  general.import = ["~/.config/alacritty/vscode-2026-dark.toml"]

[colors.primary]
background = {q(p['bg'])}
foreground = {q(p['fg'])}
dim_foreground = {q(p['fg_tab_inactive'])}

[colors.cursor]
text   = {q(p['bg'])}
cursor = {q(p['cursor'])}

[colors.selection]
text       = "CellForeground"
background = {q(p['selection'])}

[colors.normal]
black   = {q(a['black'])}
red     = {q(a['red'])}
green   = {q(a['green'])}
yellow  = {q(a['yellow'])}
blue    = {q(a['blue'])}
magenta = {q(a['magenta'])}
cyan    = {q(a['cyan'])}
white   = {q(a['white'])}

[colors.bright]
black   = {q(a['bright_black'])}
red     = {q(a['bright_red'])}
green   = {q(a['bright_green'])}
yellow  = {q(a['bright_yellow'])}
blue    = {q(a['bright_blue'])}
magenta = {q(a['bright_magenta'])}
cyan    = {q(a['bright_cyan'])}
white   = {q(a['bright_white'])}
'''

def kitty(p, a):
    return f'''# VS Code Dark 2026 -- generated by tools/gen_terminal.py
# include this file from kitty.conf:  include vscode-2026-dark.conf
background            {p['bg']}
foreground            {p['fg']}
cursor                {p['cursor']}
cursor_text_color     {p['bg']}
selection_background  {p['selection']}
selection_foreground  {p['fg']}
url_color             {a['blue']}
active_tab_background   {p['bg_tab_active']}
active_tab_foreground   {p['fg_tab_active']}
inactive_tab_background {p['bg_tab_inactive']}
inactive_tab_foreground {p['fg_tab_inactive']}

color0  {a['black']}
color8  {a['bright_black']}
color1  {a['red']}
color9  {a['bright_red']}
color2  {a['green']}
color10 {a['bright_green']}
color3  {a['yellow']}
color11 {a['bright_yellow']}
color4  {a['blue']}
color12 {a['bright_blue']}
color5  {a['magenta']}
color13 {a['bright_magenta']}
color6  {a['cyan']}
color14 {a['bright_cyan']}
color7  {a['white']}
color15 {a['bright_white']}
'''

def ghostty(p, a):
    lines = [
        '# VS Code Dark 2026 -- generated by tools/gen_terminal.py',
        '# Put in ~/.config/ghostty/themes/vscode-2026-dark then set: theme = vscode-2026-dark',
        f"background = {p['bg'].lstrip('#')}",
        f"foreground = {p['fg'].lstrip('#')}",
        f"cursor-color = {p['cursor'].lstrip('#')}",
        f"selection-background = {p['selection'].lstrip('#')}",
        f"selection-foreground = {p['fg'].lstrip('#')}",
    ]
    order = ['black','red','green','yellow','blue','magenta','cyan','white',
             'bright_black','bright_red','bright_green','bright_yellow',
             'bright_blue','bright_magenta','bright_cyan','bright_white']
    for i, k in enumerate(order):
        lines.append(f"palette = {i}={a[k]}")
    return '\n'.join(lines) + '\n'

def wezterm(p, a):
    order = ['black','red','green','yellow','blue','magenta','cyan','white']
    br = ['bright_'+k for k in order]
    return f'''-- VS Code Dark 2026 -- generated by tools/gen_terminal.py
-- return this from your wezterm config as `colors = require("vscode-2026-dark")`
return {{
  foreground = "{p['fg']}",
  background = "{p['bg']}",
  cursor_bg = "{p['cursor']}",
  cursor_fg = "{p['bg']}",
  cursor_border = "{p['cursor']}",
  selection_bg = "{p['selection']}",
  selection_fg = "{p['fg']}",
  ansi = {{ {', '.join('"%s"' % a[k] for k in order)} }},
  brights = {{ {', '.join('"%s"' % a[k] for k in br)} }},
  tab_bar = {{
    background = "{p['bg_tab_inactive']}",
    active_tab = {{ bg_color = "{p['bg_tab_active']}", fg_color = "{p['fg_tab_active']}" }},
    inactive_tab = {{ bg_color = "{p['bg_tab_inactive']}", fg_color = "{p['fg_tab_inactive']}" }},
  }},
}}
'''

def tmux(p, a):
    return f'''# VS Code Dark 2026 -- generated by tools/gen_terminal.py
# source-file this from ~/.tmux.conf
set -g default-terminal "tmux-256color"
set -ga terminal-overrides ",*256col*:Tc"

set -g status-style "bg={p['bg_statusline']},fg={p['fg_tab_inactive']}"
set -g status-left-style "bg={p['bg_statusline']},fg={p['fg']}"
set -g status-right-style "bg={p['bg_statusline']},fg={p['fg_tab_inactive']}"
set -g window-status-current-style "bg={p['bg_tab_active']},fg={p['fg_tab_active']},bold"
set -g window-status-style "bg={p['bg_tab_inactive']},fg={p['fg_tab_inactive']}"
set -g pane-border-style "fg={p['border']}"
set -g pane-active-border-style "fg={p['accent']}"
set -g message-style "bg={p['bg_float']},fg={p['fg']}"
set -g mode-style "bg={p['selection']},fg={p['fg']}"
'''

if __name__ == '__main__':
    lua = sys.argv[1]; outdir = sys.argv[2]
    p, a = read_palette(lua)
    os.makedirs(outdir, exist_ok=True)
    files = {
        'alacritty/vscode-2026-dark.toml': alacritty(p, a),
        'kitty/vscode-2026-dark.conf': kitty(p, a),
        'ghostty/vscode-2026-dark': ghostty(p, a),
        'wezterm/vscode-2026-dark.lua': wezterm(p, a),
        'tmux/vscode-2026-dark.conf': tmux(p, a),
    }
    for rel, content in files.items():
        dest = os.path.join(outdir, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        open(dest, 'w').write(content)
        print('wrote', dest)
